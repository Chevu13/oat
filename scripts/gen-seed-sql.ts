// Generates supabase/seed.sql from src/lib/data/seed.ts (single source of truth for the catalog).
// Run: node scripts/gen-seed-sql.ts
import { writeFileSync } from "node:fs";
import { seedCategories, seedProducts, DEMO_MISSING } from "../src/lib/data/seed.ts";

const q = (s: string | null | undefined) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(q).join(", ")}]::text[]`;

let sql = "-- Generated by scripts/gen-seed-sql.ts — demo catalog (prices are DEMO values, see missing_info).\n\n";
for (const c of seedCategories)
  sql += `insert into public.categories (slug, name, description, sort) values (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${c.sort}) on conflict (slug) do nothing;\n`;
sql += "\n";
seedProducts.forEach((p, i) => {
  sql += `with prod as (
  insert into public.products (slug, name, tagline, description, category_id, images, accent, missing_info, is_featured, sort)
  values (${q(p.slug)}, ${q(p.name)}, ${q(p.tagline)}, ${q(p.description)}, (select id from public.categories where slug = ${q(p.category)}),
          ${arr(p.images)}, ${q(p.accent)}, ${arr(DEMO_MISSING)}, ${Boolean(p.featured)}, ${i})
  on conflict (slug) do nothing returning id
)
insert into public.product_variants (product_id, name, price, sale_price, stock, sort)
select prod.id, v.name, v.price, v.sale_price, v.stock, v.sort from prod, (values
${p.variants.map((v, j) => `  (${q(v.name)}, ${v.price}, ${v.sale_price ?? "null::int"}, ${v.stock}, ${j})`).join(",\n")}
) as v(name, price, sale_price, stock, sort);\n\n`;
});
writeFileSync("supabase/seed.sql", sql);
console.log("wrote supabase/seed.sql");
